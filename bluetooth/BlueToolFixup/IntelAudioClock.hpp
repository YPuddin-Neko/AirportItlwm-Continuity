inline bool apply(void *data, size_t size) {
    if (!data || size < PageOffset + sizeof(Original))
        return false;
    auto bytes = static_cast<uint8_t *>(data) + PageOffset;
    for (size_t i = 0; i < sizeof(Original); ++i)
        if (bytes[i] != Original[i])
            return false;
    // Accept the local clock independently of the unused connection lookup.
    bytes[BranchOffset] = 0xeb;
    return true;
}
