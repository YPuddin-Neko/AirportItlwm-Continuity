static constexpr size_t PageOffset = 0x31e;
static constexpr size_t ScanOffset = 0;
static constexpr size_t ConnectionOffset = 0x52;
static constexpr size_t SetsOffset = 0xbe;

inline bool apply(void *data, size_t size) {
    if (size < PageOffset + sizeof(Original))
        return false;
    auto bytes = static_cast<uint8_t *>(data) + PageOffset;
    for (size_t i = 0; i < sizeof(Original); ++i)
        if (bytes[i] != Original[i])
            return false;
    // All three selectors occupy this one page. Check the whole group first.
    for (size_t i = 0; i < sizeof(StandardScan); ++i) {
        bytes[ScanOffset + i] = StandardScan[i];
        bytes[ConnectionOffset + i] = StandardScan[i];
    }
    for (size_t i = 0; i < sizeof(StandardSets); ++i)
        bytes[SetsOffset + i] = StandardSets[i];
    return true;
}
